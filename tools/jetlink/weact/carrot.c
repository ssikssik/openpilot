#include "carrot.h"
#include "bootloader.h"
#include "fdcan.h"
#include "usbd_cdc_if.h"
#include <string.h>

extern USBD_HandleTypeDef hUsbDeviceFS;
extern uint8_t UserRxBufferFS[];
extern uint8_t UserTxBufferFS[];

static const char hex[] = "0123456789ABCDEF";
static const char version[] = "carrot-weact-ev4-tx-sync-1\r";
static const uint32_t errors = FDCAN_IR_PEA | FDCAN_IR_PED | FDCAN_IR_BO;
static volatile uint32_t usb_length;
static volatile uint8_t disconnect;
static char command[37];
static uint32_t command_length, usb_offset, output_length;
static uint32_t tx_buffer, last_query;
static uint16_t sequence;
static uint8_t host_completed, sync_enabled;
static uint8_t correction[16], correction_armed, correction_pending, correction_fault;
static uint32_t correction_tick, correction_buffer, correction_start, correction_max_ms, correction_count;
static uint8_t opened, normal, discard, tx_failed;

void carrot_usb_receive(uint32_t length)
{
    usb_length = length;
}

void carrot_usb_disconnect(void)
{
    disconnect = 1;
}

static void close_can(void)
{
    if (opened) {
        HAL_FDCAN_AbortTxRequest(&hfdcan1, FDCAN_TX_BUFFER0 | FDCAN_TX_BUFFER1 | FDCAN_TX_BUFFER2);
    }
    // Reset the controller, including its pending TX requests and message FIFOs.
    __HAL_RCC_FDCAN_FORCE_RESET();
    __HAL_RCC_FDCAN_RELEASE_RESET();
    hfdcan1.State = HAL_FDCAN_STATE_RESET;
    opened = normal = tx_failed = 0;
    tx_buffer = 0;
    host_completed = sync_enabled = 0;
    correction_armed = correction_pending = correction_fault = 0;
    correction_buffer = 0;
}

static uint8_t open_can(void)
{
    hfdcan1.Init.Mode = normal ? FDCAN_MODE_NORMAL : FDCAN_MODE_BUS_MONITORING;
    hfdcan1.Init.AutoRetransmission = DISABLE;
    hfdcan1.Init.FrameFormat = FDCAN_FRAME_FD_BRS;
    hfdcan1.Init.NominalPrescaler = 1;
    hfdcan1.Init.NominalSyncJumpWidth = 14;
    hfdcan1.Init.NominalTimeSeg1 = 104;
    hfdcan1.Init.NominalTimeSeg2 = 15;
    hfdcan1.Init.DataPrescaler = 2;
    hfdcan1.Init.DataSyncJumpWidth = 6;
    hfdcan1.Init.DataTimeSeg1 = 22;
    hfdcan1.Init.DataTimeSeg2 = 7;
    hfdcan1.Init.StdFiltersNbr = 2;
    if (HAL_FDCAN_Init(&hfdcan1) != HAL_OK ||
        HAL_FDCAN_ConfigGlobalFilter(&hfdcan1, FDCAN_REJECT, FDCAN_REJECT,
                                    FDCAN_REJECT_REMOTE, FDCAN_REJECT_REMOTE) != HAL_OK) {
        close_can();
        return 0;
    }
    FDCAN_FilterTypeDef filter = {
        .IdType = FDCAN_STANDARD_ID, .FilterIndex = 0, .FilterType = FDCAN_FILTER_MASK,
        .FilterConfig = FDCAN_FILTER_TO_RXFIFO0, .FilterID1 = 0x3e3, .FilterID2 = 0x7ff,
    };
    if (HAL_FDCAN_ConfigFilter(&hfdcan1, &filter) != HAL_OK) {
        close_can();
        return 0;
    }
    filter.FilterIndex = 1;
    filter.FilterType = FDCAN_FILTER_DUAL;
    filter.FilterID1 = 0x35a;
    filter.FilterID2 = 0x35b;
    if (HAL_FDCAN_ConfigFilter(&hfdcan1, &filter) != HAL_OK) {
        close_can();
        return 0;
    }
    if (HAL_FDCAN_Start(&hfdcan1) != HAL_OK) {
        close_can();
        return 0;
    }
    last_query = HAL_GetTick();
    opened = 1;
    return 1;
}

static void append(const void *data, uint32_t length)
{
    memcpy(UserTxBufferFS + output_length, data, length);
    output_length += length;
}

static void put_hex(char *dest, uint32_t value, uint32_t digits)
{
    while (digits) {
        dest[--digits] = hex[value & 15];
        value >>= 4;
    }
}

static void report(void)
{
    last_query = HAL_GetTick();
    FDCAN_GlobalTypeDef *can = hfdcan1.Instance;
    uint32_t control = can->CCCR;
    uint32_t psr = can->PSR;
    uint32_t ir = can->IR;
    uint32_t ecr = can->ECR;
    char response[32] = "QC0";
    if (opened) {
        response[1] = 'E';
        if (!(control & (FDCAN_CCCR_INIT | FDCAN_CCCR_TEST)) && !(psr & FDCAN_PSR_BO)) {
            if (control & FDCAN_CCCR_MON) response[1] = 'L';
            else if (control & FDCAN_CCCR_DAR) response[1] = 'T';
        }
    }
    if (correction_fault || tx_failed || (tx_buffer && (ir & errors))) response[2] = '3';
    else if (host_completed) response[2] = '2';
    else if (tx_buffer) {
        if (can->TXBRP & tx_buffer) response[2] = '1';
        else if (can->TXBTO & tx_buffer) response[2] = '2';
        else if (can->TXBCF & tx_buffer) response[2] = '4';
        else response[2] = '1';
    }
    put_hex(response + 3, sequence, 4);
    put_hex(response + 7, psr, 8);
    put_hex(response + 15, ir, 8);
    put_hex(response + 23, ecr, 8);
    response[31] = '\r';
    append(response, sizeof(response));
}

// EV4 payload CRC, separate from the CAN FD wire CRC generated by FDCAN.
static uint16_t ev4_crc(const uint8_t data[16])
{
    uint16_t crc = 0;
    for (unsigned i = 2; i < 18; i++) {
        const uint8_t byte = i < 16 ? data[i] : (i == 16 ? 0xe3 : 0x03);
        crc ^= (uint16_t)byte << 8;
        for (unsigned bit = 0; bit < 8; bit++)
            crc = (uint16_t)((crc << 1) ^ ((crc & 0x8000) ? 0x1021 : 0));
    }
    return crc ^ 0x041d;
}

static uint8_t queue_ev4(uint8_t data[16])
{
    FDCAN_TxHeaderTypeDef header = {
        .Identifier = 0x3e3, .IdType = FDCAN_STANDARD_ID, .TxFrameType = FDCAN_DATA_FRAME,
        .DataLength = FDCAN_DLC_BYTES_16, .ErrorStateIndicator = FDCAN_ESI_ACTIVE,
        .BitRateSwitch = FDCAN_BRS_ON, .FDFormat = FDCAN_FD_CAN,
        .TxEventFifoControl = FDCAN_NO_TX_EVENTS,
    };
    return HAL_FDCAN_AddMessageToTxFifoQ(&hfdcan1, &header, data) == HAL_OK;
}

static void poll_correction(void)
{
    if (!correction_pending) return;
    FDCAN_GlobalTypeDef *can = hfdcan1.Instance;
    if (can->IR & errors || HAL_GetTick() - correction_start >= 15) {
        HAL_FDCAN_AbortTxRequest(&hfdcan1, correction_buffer);
        correction_fault = 1;
        correction_armed = 0;
        correction_pending = 0;
    } else if (!(can->TXBRP & correction_buffer)) {
        correction_pending = 0;
        if (can->TXBTO & correction_buffer) {
            uint32_t elapsed = HAL_GetTick() - correction_start;
            if (elapsed > correction_max_ms) correction_max_ms = elapsed;
            correction_count++;
        }
    }
}

static void correct_oem(const uint8_t data[16])
{
    if (!normal || !sync_enabled || ev4_crc(data) != ((uint16_t)data[0] | ((uint16_t)data[1] << 8))) return;
    if (data[9] != 1 || data[11] != 0 || data[12] != 0) {
        correction_armed = 0;
        correction_fault = 1;
        if (correction_pending) HAL_FDCAN_AbortTxRequest(&hfdcan1, correction_buffer);
        return;
    }
    FDCAN_GlobalTypeDef *can = hfdcan1.Instance;
    if (!correction_armed || correction_pending || correction_fault || disconnect ||
        HAL_GetTick() - correction_tick >= 55 || can->IR & errors ||
        (tx_buffer && !(can->TXBTO & tx_buffer))) return;
    if (!(can->CCCR & FDCAN_CCCR_DAR) || (can->CCCR & (FDCAN_CCCR_INIT | FDCAN_CCCR_MON))) return;
    correction_armed = 0;
    host_completed = 1;
    correction_start = HAL_GetTick();
    if (queue_ev4(correction)) {
        correction_buffer = HAL_FDCAN_GetLatestTxFifoQRequestBuffer(&hfdcan1);
        correction_pending = 1;
    } else {
        correction_fault = 1;
    }
}

static uint8_t send_frame(void)
{
    FDCAN_GlobalTypeDef *can = hfdcan1.Instance;
    if (!opened || !normal || (can->CCCR & (FDCAN_CCCR_INIT | FDCAN_CCCR_MON | FDCAN_CCCR_TEST)) ||
        !(can->CCCR & FDCAN_CCCR_DAR) || (can->TXBRP & tx_buffer) ||
        memcmp(command, "b3E3A", 5) != 0) return 0;
    uint8_t data[16];
    for (uint32_t i = 0; i < 16; i++) {
        const char *hi = memchr(hex, command[5 + 2*i], 16);
        const char *lo = memchr(hex, command[6 + 2*i], 16);
        if (!hi || !lo || !*hi || !*lo) return 0;
        data[i] = (uint8_t)((hi - hex) * 16 + (lo - hex));
    }
    const uint8_t lever = data[9];
    if ((lever != 0x01 && lever != 0x45 && lever != 0x11) ||
        ev4_crc(data) != ((uint16_t)data[0] | ((uint16_t)data[1] << 8))) return 0;
    correction_armed = 0;
    if (correction_pending || correction_fault) return 0;
    can->IR = errors;
    host_completed = 0;
    sequence++;
    tx_failed = !queue_ev4(data);
    tx_buffer = tx_failed ? 0 : HAL_FDCAN_GetLatestTxFifoQRequestBuffer(&hfdcan1);
    if (sync_enabled && !tx_failed && (data[11] == 0x24 || data[11] == 0x90 || data[11] == 0xb4)) {
        memcpy(correction, data, sizeof(correction));
        correction_tick = HAL_GetTick();
        correction_armed = 1;
    }
    return 1;
}

static void process_command(void)
{
    if (command_length == 1) {
        switch (command[0]) {
        case 'C': close_can(); return;
        case 'V': append(version, sizeof(version) - 1); return;
        case 'Q': report(); return;
        case 'J': {
            char stats[18] = "J";
            put_hex(stats + 1, correction_count, 8);
            put_hex(stats + 9, correction_max_ms, 8);
            stats[17] = '\r';
            append(stats, sizeof(stats));
            return;
        }
        case 'O': if (!opened && open_can()) return; break;
        case 'X': close_can(); bootloader_enter_update_mode(); return;
        }
    }
    if (!opened && command_length == 2) {
        if (memcmp(command, "K1", 2) == 0) { sync_enabled = 1; return; }
        if (memcmp(command, "S6", 2) == 0 || memcmp(command, "Y1", 2) == 0 ||
            memcmp(command, "A0", 2) == 0) return;
        if (command[0] == 'M' && (command[1] == '0' || command[1] == '1')) {
            normal = command[1] == '0';
            return;
        }
    }
    if (command_length == sizeof(command) && send_frame()) return;
    append("\a\r", 2);
}

static void receive_can(uint8_t usb_ready)
{
    for (unsigned count = 0; count < 16 && opened &&
           HAL_FDCAN_GetRxFifoFillLevel(&hfdcan1, FDCAN_RX_FIFO0); count++) {
        FDCAN_RxHeaderTypeDef header;
        uint8_t data[64];
        if (HAL_FDCAN_GetRxMessage(&hfdcan1, FDCAN_RX_FIFO0, &header, data) != HAL_OK) break;
        if (header.IdType != FDCAN_STANDARD_ID || header.FDFormat != FDCAN_FD_CAN ||
            header.RxFrameType != FDCAN_DATA_FRAME || header.DataLength != FDCAN_DLC_BYTES_16 ||
            (header.Identifier != 0x3e3 && header.Identifier != 0x35a &&
             header.Identifier != 0x35b)) continue;
        if (header.Identifier == 0x3e3 && header.BitRateSwitch == FDCAN_BRS_ON)
            correct_oem(data);
        if (!usb_ready || output_length >= APP_TX_DATA_SIZE - 64) continue;
        char line[38] = "b3E3A";
        if (header.BitRateSwitch == FDCAN_BRS_OFF) line[0] = 'd';
        put_hex(line + 1, header.Identifier, 3);
        for (uint32_t i = 0; i < 16; i++) put_hex(line + 5 + 2*i, data[i], 2);
        line[37] = '\r';
        append(line, sizeof(line));
    }
}

void carrot_poll(void)
{
    if (opened && normal && HAL_GetTick() - last_query >= 750) close_can();
    if (disconnect) {
        disconnect = 0;
        close_can();
        usb_length = usb_offset = command_length = discard = output_length = 0;
    }
    // The USB interrupt owns transfer state and keeps the output buffer until completion.
    __disable_irq();
    USBD_CDC_HandleTypeDef *cdc = hUsbDeviceFS.pClassData;
    uint8_t ready = hUsbDeviceFS.dev_state == USBD_STATE_CONFIGURED && cdc && !cdc->TxState;
    __enable_irq();
    poll_correction();
    receive_can(ready);
    if (!ready || correction_pending) return;

    while (usb_offset < usb_length && output_length < APP_TX_DATA_SIZE - 64) {
        char byte = (char)UserRxBufferFS[usb_offset++];
        if (byte == '\r') {
            if (disconnect) break;
            if (discard) append("\a\r", 2);
            else if (command_length) process_command();
            command_length = discard = 0;
        } else if (command_length == sizeof(command)) {
            discard = 1;
        } else {
            command[command_length++] = byte;
        }
    }
    __disable_irq();
    if (!disconnect && hUsbDeviceFS.dev_state == USBD_STATE_CONFIGURED) {
        if (usb_length && usb_offset == usb_length) {
            usb_length = usb_offset = 0;
            USBD_CDC_ReceivePacket(&hUsbDeviceFS);
        }
        if (output_length && CDC_Transmit_FS(UserTxBufferFS, output_length) == USBD_OK) {
            output_length = 0;
        }
    }
    __enable_irq();
}
